#!/usr/bin/env python3
"""Audit original bytes and decoded AAC tones; no speaker/language claim."""
import argparse
from array import array
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import multiaudio_contract as contract
from multiaudio_tone import decoded_frequency

parser = argparse.ArgumentParser()
parser.add_argument("--media", required=True)
args = parser.parse_args()
root = Path(args.media).resolve(strict=True)
repository = Path(__file__).resolve().parents[3]
if root == repository or repository in root.parents or not root.name.startswith("reel-tvos-fixture-"):
    raise SystemExit("Use the owned generated fixture outside source.")
manifest = json.loads((root / "multiaudio-media.json").read_text())
for relative, expected in manifest["files"].items():
    path = root / relative
    if Path(relative).is_absolute() or path.is_symlink() or not path.resolve(strict=True).is_relative_to(root):
        raise SystemExit("Unsafe manifest resource")
    assert hashlib.sha256(path.read_bytes()).hexdigest() == expected, relative
for audio in [1, 3]:
    for subtitle in [-1, 2]:
        path = contract.media_file(root, f"master-a{audio}-s{subtitle}.m3u8")
        data = path.read_bytes()
        assert data.count(b"TYPE=AUDIO") == 2 and data.count(b"TYPE=SUBTITLES") == 1
        assert b'LANGUAGE="en"' in data and b'LANGUAGE="es"' in data
        assert contract.playlist(data, audio, subtitle, "master.m3u8").count(b"ApiKey=fixture-tv-multiaudio") == 4
for group in ["video", "en", "es"]:
    contract.playlist(contract.media_file(root, f"{group}/index.m3u8").read_bytes(), 1, -1, f"{group}/index.m3u8")

audits = []
for language, expected in [("en", 440), ("es", 880)]:
    playlist = contract.media_file(root, f"{language}/index.m3u8")
    raw = subprocess.check_output(["ffmpeg", "-hide_banner", "-loglevel", "error", "-ss", "1", "-i", str(playlist), "-t", "2", "-vn", "-ac", "1", "-ar", "48000", "-f", "s16le", "-"])
    samples = array("h"); samples.frombytes(raw)
    if sys.byteorder != "little": samples.byteswap()
    measured = decoded_frequency(samples)
    assert abs(measured["decodedZeroCrossingHz"] - expected) <= 1, (language, measured)
    audits.append({"languageMetadata": language, "expectedToneHz": expected, **measured})
assert contract.CAPTION in contract.media_file(root, "captions/cue.vtt").read_text()
print(json.dumps({"result": "passed", "scope": "Generated bytes, strict local playlist references and decoded tone identity; no native selection, spoken-language, acoustic or physical output claim", "manifestSHA256": hashlib.sha256((root / "multiaudio-media.json").read_bytes()).hexdigest(), "files": len(manifest["files"]), "decodedAudio": audits}, indent=2))
